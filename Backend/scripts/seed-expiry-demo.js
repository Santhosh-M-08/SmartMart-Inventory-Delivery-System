/* SmartMart Expiry — OPTIONAL demo seed (NEW FILE)  File: Backend/scripts/seed-expiry-demo.js
   Creates batches flagged source:"sample" for products in data/products.json, with dates relative to today.
   Run:    node scripts/seed-expiry-demo.js          (add demo batches)
           node scripts/seed-expiry-demo.js --clear  (remove ONLY the demo batches and their sales/alerts)
   Real batches (source:"actual") are never touched. */
'use strict';
const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');
const { Batch, Sale, Notification } = require('../expiry/models');
const R = require('../expiry/rules');

(async () => {
  await mongoose.connect(process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/smartmart', { serverSelectionTimeoutMS: 5000 });
  const sampleBatches = await Batch.find({ source: 'sample' }).select('_id').lean();
  const ids = sampleBatches.map(b => b._id);
  if (ids.length) {
    await Promise.all([Sale.deleteMany({ batchId: { $in: ids } }), Notification.deleteMany({ batchId: { $in: ids } }), Batch.deleteMany({ _id: { $in: ids } })]);
    console.log('Removed ' + ids.length + ' sample batches.');
  }
  if (process.argv.includes('--clear')) return;

  let products = [];
  try { products = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'products.json'), 'utf8')); }
  catch (e) { console.log('No data/products.json yet. Start the server once (GET /api/products) and run this again.'); return; }
  products = products.filter(p => p.stock > 0);
  if (!products.length) { console.log('No products with stock.'); return; }

  const t = R.todayISO();
  const plans = [
    { off: 3, qty: 24, disc: [[0, 6]] }, { off: 2, qty: 18, disc: [[-1, 4], [0, 4]] }, { off: 0, qty: 12, disc: [[-2, 5], [-1, 4]] },
    { off: -1, qty: 6, disc: [[-4, 5], [-3, 4], [-2, 5]] }, { off: 6, qty: 16, full: [[-2, 4]] }, { off: 12, qty: 30, full: [[-3, 5]] }
  ];
  let n = 0;
  for (let i = 0; i < plans.length; i++) {
    const p = products[i % products.length], plan = plans[i];
    const batchNo = (String(p.name).match(/[A-Za-z]+/) || ['BAT'])[0].toUpperCase().slice(0, 4) + (900 + i);
    const base = Number(p.price), disc = R.round2(base * 0.5);
    const sales = [];
    (plan.disc || []).forEach(d => sales.push({ date: R.addDays(t, d[0]), qty: d[1], unitPrice: disc, basePrice: base, discountPct: 50 }));
    (plan.full || []).forEach(d => sales.push({ date: R.addDays(t, d[0]), qty: d[1], unitPrice: base, basePrice: base, discountPct: 0 }));
    const sold = sales.reduce((a, s) => a + s.qty, 0), qty = Math.max(1, Math.min(p.stock, plan.qty));
    const b = await Batch.create({ productId: p.id, batchNo, qtyReceived: qty + sold, qtyAvailable: qty, expiryDate: R.addDays(t, plan.off), receivedDate: R.addDays(t, plan.off - 14), source: 'sample' });
    if (sales.length) await Sale.insertMany(sales.map(s => Object.assign({ batchId: b._id, productId: p.id, orderRef: 'SAMPLE' }, s)));
    n++;
  }
  console.log('Created ' + n + ' sample batches (source: "sample"). Expiry alerts are generated by the server job or POST /api/expiry/sync.');
})().catch(e => { console.error(e.message); process.exitCode = 1; }).finally(() => mongoose.disconnect());